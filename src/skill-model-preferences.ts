const preferences = new Map<string, readonly [Role, Role, Role, Role]>();
for (const group of Object.keys(groups) as (keyof typeof groups)[]) {
  for (const id of groups[group]) {
    if (preferences.has(id)) throw new Error(`重复的技能模型优先级：${id}`);
    preferences.set(id, orders[group]);
  }
}

export function skillModelPreference(id: string): readonly [Role, Role, Role, Role] {
  const preference = preferences.get(id);
  if (!preference) throw new Error(`缺少技能模型优先级：${id}`);
  return preference;
}
